import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {TextEncoder} from 'node:util';
const ctx=vm.createContext({TextEncoder,HTMLElement:class {}});
vm.runInContext(readFileSync(new URL('../custom_components/intercom_m3_poc/frontend/panel.js',import.meta.url),'utf8'),ctx);
const P=ctx.IntercomM3FrontendTest.IntercomM3PocPanel;
const nodes=new Map();
const p=Object.create(P.prototype);
p.shadowRoot={innerHTML:'',querySelector(s){if(!nodes.has(s))nodes.set(s,{setAttribute(k,v){this[k]=v}});return nodes.get(s)}};
Object.assign(p,{panelConfig:{compact:true,device_id:'room'},metrics:{simulation:false,backend:'IDLE',server:{}},rooms:[{deviceId:'room',name:'Living Room',available:true,busy:false}],selectedDeviceId:'room',callMode:'full_duplex',status:'Ready'});
let called=0,hung=0,muted=0;
p.call=()=>called++;p.cleanup=()=>hung++;p.toggleMute=()=>muted++;
p.render();
assert.equal(nodes.get('#call').textContent,'Call');assert.equal(nodes.get('#call').hidden,false);
assert.equal(nodes.get('#hang').hidden,true);assert.equal(nodes.get('#mute').hidden,true);
assert.match(p.shadowRoot.innerHTML,/#call\{background:#216e39\}/);
nodes.get('#call').onclick();assert.equal(called,1);
p.callId='call';p.inflight=true;p.status='CONNECTED to authenticated room endpoint';p.render();
assert.equal(nodes.get('#call').hidden,true);assert.equal(nodes.get('#hang').textContent,'Hangup');assert.equal(nodes.get('#hang').hidden,false);
assert.equal(nodes.get('#mute').hidden,false);assert.equal(nodes.get('#mute').textContent,'Mute');assert.equal(nodes.get('#mute')['aria-pressed'],'false');
nodes.get('#mute').onclick();assert.equal(muted,1);
p.softMuted=true;p.render();assert.equal(nodes.get('#mute').textContent,'Unmute');assert.equal(nodes.get('#mute')['aria-pressed'],'true');
nodes.get('#hang').onclick();assert.equal(hung,1);
p.callId=null;p.inflight=false;p.softMuted=false;p.status='USER_HANGUP';p.render();
assert.equal(nodes.get('#call').hidden,false);assert.equal(nodes.get('#hang').hidden,true);assert.equal(nodes.get('#mute').hidden,true);
assert.equal(nodes.get('#status').textContent,'Ready to call');
p.status='PANEL_REMOVED';p.render();assert.equal(nodes.get('#status').textContent,'Ready to call');
console.log('PASS compact call, hangup, mute/unmute and cleanup reuse the real call handlers');
